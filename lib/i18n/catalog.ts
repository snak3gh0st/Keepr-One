export type MessageKey = keyof typeof messages;
export type MessageValues = Record<string, string | number>;

function interpolate(template: string, values: MessageValues = {}) {
  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(values[token] ?? `{${token}}`));
}

export function translate(language: UserLanguage, key: MessageKey, values: MessageValues = {}) {
  return interpolate(messages[key][language], values);
}

export function localize(
  language: UserLanguage,
  portuguese: string,
  english: string,
  values: MessageValues = {},
) {
  return interpolate(language === "PT" ? portuguese : english, values);
}
